export const userRole = pgEnum('user_role', ['user', 'moderator', 'admin']);
export const userStatus = pgEnum('user_status', ['active', 'paused', 'suspended']);

export const user = pgTable('user', {
  id: text('id').primaryKey(),
  name: text('name').notNull().default(''),
  email: text('email').notNull().unique(),
  emailVerified: boolean('email_verified').notNull().default(false),
  image: text('image'),
  role: userRole('role').notNull().default('user'),
  status: userStatus('status').notNull().default('active'),
  suspendedReason: varchar('suspended_reason', { length: 32 }),
  /** Inactivity deletion (optional, off by default): when the 30-day warning was emailed. */
  inactivityNoticeAt: timestamp('inactivity_notice_at', { withTimezone: true }),
  /** Last sign-in or session refresh (at most daily); used only for the optional inactivity rule. */
  lastSeenAt: timestamp('last_seen_at', { withTimezone: true }).notNull().defaultNow(),
  /** "Take a break" (phase 18a): hidden from new people since then. */
  pausedAt: timestamp('paused_at', { withTimezone: true }),
  /** When the break ends by itself; null with pausedAt set means "until I turn it back on". */
  pausedUntil: timestamp('paused_until', { withTimezone: true }),
  /** Incognito (phase 18b): only people this member liked can see them. */
  incognito: boolean('incognito').notNull().default(false),
  ...timestamps,
});

