import { sql } from 'drizzle-orm';
import {
  bigint,
  boolean,
  check,
  customType,
  date,
  index,
  integer,
  jsonb,
  pgEnum,
  pgTable,
  smallint,
  text,
  timestamp,
  uniqueIndex,
  uuid,
  varchar,
  vector,
} from 'drizzle-orm/pg-core';
import {
  consentKinds,
  moderationActions,
  reportCategories,
  reportPriorities,
  reportStatuses,
  verificationPoses,
  EMBEDDING_DIM,
  genders,
  intentions,
  interactionKinds,
  photoStatuses,
  promptKeys,
} from '@dateos/shared';

const timestamps = {
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true })
    .notNull()
    .defaultNow()
    .$onUpdate(() => new Date()),
};

// ---------------------------------------------------------------------------
// Auth tables, shaped as better-auth expects (ids are generated by better-auth).
// ---------------------------------------------------------------------------

export const userRole = pgEnum('user_role', ['user', 'moderator', 'admin']);
export const userStatus = pgEnum('user_status', ['active', 'paused', 'suspended']);

export const user = pgTable('user', {
  id: text('id').primaryKey(),
  name: text('name').notNull().default(''),
  email: text('email').notNull().unique(),
  emailVerified: boolean('email_verified').notNull().default(false),
  image: text('image'),
  role: userRole('role').notNull().default('user'),
  status: userStatus('status').notNull().default('active'),
  suspendedReason: varchar('suspended_reason', { length: 32 }),
  ...timestamps,
});

export const session = pgTable(
  'session',
  {
    id: text('id').primaryKey(),
    token: text('token').notNull().unique(),
    expiresAt: timestamp('expires_at', { withTimezone: true }).notNull(),
    ipAddress: text('ip_address'),
    userAgent: text('user_agent'),
    userId: text('user_id')
      .notNull()
      .references(() => user.id, { onDelete: 'cascade' }),
    ...timestamps,
  },
  (t) => [index('session_user_id_idx').on(t.userId)],
);

export const account = pgTable(
  'account',
  {
    id: text('id').primaryKey(),
    accountId: text('account_id').notNull(),
    providerId: text('provider_id').notNull(),
    userId: text('user_id')
      .notNull()
      .references(() => user.id, { onDelete: 'cascade' }),
    accessToken: text('access_token'),
    refreshToken: text('refresh_token'),
    idToken: text('id_token'),
    accessTokenExpiresAt: timestamp('access_token_expires_at', { withTimezone: true }),
    refreshTokenExpiresAt: timestamp('refresh_token_expires_at', { withTimezone: true }),
    scope: text('scope'),
    password: text('password'),
    ...timestamps,
  },
  (t) => [index('account_user_id_idx').on(t.userId)],
);

export const verification = pgTable(
  'verification',
  {
    id: text('id').primaryKey(),
    identifier: text('identifier').notNull(),
    value: text('value').notNull(),
    expiresAt: timestamp('expires_at', { withTimezone: true }).notNull(),
    ...timestamps,
  },
  (t) => [index('verification_identifier_idx').on(t.identifier)],
);

export const rateLimit = pgTable('rate_limit', {
  id: text('id').primaryKey(),
  key: text('key').notNull().unique(),
  count: integer('count').notNull(),
  lastRequest: bigint('last_request', { mode: 'number' }).notNull(),
});

// ---------------------------------------------------------------------------
// Product tables. Every row is owned by a user and removed when the user is deleted.
// ---------------------------------------------------------------------------

export const gender = pgEnum('gender', genders);
export const intention = pgEnum('intention', intentions);
export const photoStatus = pgEnum('photo_status', photoStatuses);
export const photoPurpose = pgEnum('photo_purpose', ['profile', 'chat', 'verification']);
export const consentKind = pgEnum('consent_kind', consentKinds);
export const promptKey = pgEnum('prompt_key', promptKeys);

const ownerId = () =>
  text('user_id')
    .notNull()
    .references(() => user.id, { onDelete: 'cascade' });

export const profiles = pgTable('profiles', {
  userId: ownerId().primaryKey(),
  displayName: varchar('display_name', { length: 40 }).notNull(),
  birthDate: date('birth_date').notNull(),
  gender: gender('gender').notNull(),
  interestedIn: gender('interested_in').array().notNull(),
  intention: intention('intention').notNull(),
  bio: varchar('bio', { length: 500 }),
  languages: text('languages')
    .array()
    .notNull()
    .default(sql`'{}'::text[]`),
  /** Set when a moderator approved a photo verification. */
  verifiedAt: timestamp('verified_at', { withTimezone: true }),
  ...timestamps,
});

export const preferences = pgTable(
  'preferences',
  {
    userId: ownerId().primaryKey(),
    ageMin: smallint('age_min').notNull(),
    ageMax: smallint('age_max').notNull(),
    maxDistanceKm: smallint('max_distance_km').notNull(),
    intentions: intention('intentions')
      .array()
      .notNull()
      .default(sql`'{}'::intention[]`),
    ...timestamps,
  },
  (t) => [check('preferences_age_range', sql`${t.ageMin} >= 18 AND ${t.ageMin} <= ${t.ageMax}`)],
);

export const prompts = pgTable(
  'prompts',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    userId: ownerId(),
    promptKey: promptKey('prompt_key').notNull(),
    answer: varchar('answer', { length: 300 }).notNull(),
    position: smallint('position').notNull(),
    ...timestamps,
  },
  (t) => [
    uniqueIndex('prompts_user_position_uq').on(t.userId, t.position),
    uniqueIndex('prompts_user_key_uq').on(t.userId, t.promptKey),
  ],
);

export const photos = pgTable(
  'photos',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    userId: ownerId(),
    status: photoStatus('status').notNull().default('quarantine'),
    /** Chat images are never listed on profiles. */
    purpose: photoPurpose('purpose').notNull().default('profile'),
    quarantineKey: text('quarantine_key'),
    mediaKey: text('media_key'),
    width: integer('width'),
    height: integer('height'),
    position: smallint('position').notNull(),
    rejectReason: varchar('reject_reason', { length: 32 }),
    ...timestamps,
  },
  (t) => [index('photos_user_id_idx').on(t.userId)],
);

/** Append-only history: the latest row per (user, kind) is the current state. */
export const consents = pgTable(
  'consents',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    userId: ownerId(),
    kind: consentKind('kind').notNull(),
    granted: boolean('granted').notNull(),
    version: varchar('version', { length: 32 }).notNull(),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [index('consents_user_kind_idx').on(t.userId, t.kind, t.createdAt)],
);

/** Security-relevant events. `meta` must never contain personal data. */
export const auditLogs = pgTable(
  'audit_logs',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    actorId: text('actor_id').references(() => user.id, { onDelete: 'set null' }),
    action: varchar('action', { length: 64 }).notNull(),
    targetType: varchar('target_type', { length: 32 }),
    targetId: text('target_id'),
    meta: jsonb('meta').$type<Record<string, string | number | boolean>>(),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [index('audit_logs_created_at_idx').on(t.createdAt)],
);

