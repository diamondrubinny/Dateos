const TEMPLATES: Record<ComplianceTemplate, Record<'en' | 'he', (f: TemplateFacts) => string>> = {
  'security-statement': { en: securityEn, he: securityHe },
  'no-paid-features': { en: pledgeEn, he: pledgeHe },
  'risk-assessment': { en: riskEn, he: riskHe },
};

export function renderTemplate(
  name: ComplianceTemplate,
  locale: 'en' | 'he',
  facts: TemplateFacts,
): string {
  return TEMPLATES[name][locale](facts);
}
