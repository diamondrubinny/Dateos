function riskEn(f: TemplateFacts): string {
  return join([
    `# Risk assessment: ${f.community}`,
    '',
    `> DRAFT starting point, generated by NexaHeart on ${f.date} from this community’s settings. It isn’t a complete assessment: add what you know about your members, and review it at least once a year and whenever the settings change. ⚖️ (UK Online Safety Act, DSA, GDPR Art. 35 may each ask for a different format.)`,
    '',
    '| Risk | Why it applies here | What NexaHeart does | What you still need to do |',
    '| --- | --- | --- | --- |',
    `| Under-age members | Anyone can claim an age | Minimum age ${f.minAge}${f.ageCheck ? ', age check at an outside provider' : ''}; reports for "under 18" are top priority | ${f.ageCheck ? 'Check the provider’s accuracy and DPA' : 'Decide whether to require an age check (Dashboard → Branding → Who may join)'} |`,
    '| Romance scams and money requests | Common on every dating service' +
      (f.minAge >= 50 ? ', and older members are targeted more often' : '') +
      ' | Automatic checks for links, contact details and money words; reports; photo copy detection | Watch the reports; tell members never to send money |',
    '| Being outed, extortion | A profile can reveal sexual orientation or gender identity | Identity shown to matches only by default; screenshots of chats can’t be blocked, so warn members | Consider the countries your members live in or travel to |',
    f.faith &&
      '| Exposure of faith or observance | Special-category data | Stored only with consent, never ranked on or sent to partners | A DPIA may be needed ⚖️ |',
    '| Harassment and threats | Messages between strangers | Blocking, reporting, filters for abusive words | Enough moderators to answer reports quickly |',
    '| Meeting in person | Dates move offline | Safety check-in with a trusted contact; date planner with public venues | Share safety tips in your own words |',
    f.videoCalls &&
      '| Video calls | Live content can’t be checked in advance | End-to-end encrypted, nothing recorded; report and block in the call | Explain that recording the other person needs their consent |',
    f.partners > 0 &&
      `| Partner communities (${f.partners}) | Their members can see and write to yours | Only members who opt in; reports and blocks travel between communities | Review each partner’s rules and privacy policy |`,
    f.friendsOnly &&
      '| Romantic or sexual approaches in a friendship community | Members joined for friendship | The friendship intention only | Say so in your community rules and act on reports |',
    f.externalAi &&
      '| Text sent to an outside AI service | Suggestions are made outside your server | Only the text needed for the suggestion | A DPA with the provider and an international transfer check ⚖️ |',
    '| Data breach | Any server can be attacked | Updates from GitHub, staff MFA, audit log, encrypted secrets | Encrypt disks and backups; record incidents (Dashboard → Compliance) |',
  ]);
}

