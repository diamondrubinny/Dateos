/**
 * Phase 64: what's actually configured in this community. Every claim a template makes comes from
 * here or from the code; anything else is left for the operator to fill in. ⚖️
 */
export interface TemplateFacts {
  community: string;
  operator: string | null;
  contact: string | null;
  date: string;
  videoCalls: boolean;
  ageCheck: boolean;
  /** Text AI on a server outside this one (OPENAI_EXTERNAL). */
  externalAi: boolean;
  partners: number;
  faith: boolean;
  /** The longer gender identity list or own words. */
  identity: boolean;
  minAge: number;
  friendsOnly: boolean;
}

type Lines = (string | false | null | undefined)[];
const join = (lines: Lines) =>
  `${lines.filter((l): l is string => typeof l === 'string').join('\n')}\n`;

// ------------------------------------------------------------------------------ English

function securityEn(f: TemplateFacts): string {
  return join([
    `# Security statement: ${f.community}`,
    '',
    `> DRAFT for legal and security review before publishing. Generated by NexaHeart on ${f.date} from this community’s settings. Don’t promise more than you do: check every line.`,
    '',
    `${f.operator ?? '[Operator name]'} runs ${f.community} on its own server with NexaHeart, open-source software anyone can inspect.`,
    '',
    '## Where your data is',
    '',
    '- On our server, hosted by [hosting provider] in [country].',
    '- Between your device and our server, everything is encrypted (HTTPS).',
    '- On disk: [say whether the server disk and backups are encrypted].',
    '- We don’t sell your data, and we don’t show ads from ad networks.',
    '',
    '## What we protect, and how',
    '',
    '- Photos are scanned for malware and re-encoded before anyone sees them, which removes hidden data such as the location the photo was taken in.',
    f.videoCalls &&
      '- Video and voice dates are end-to-end encrypted: our server forwards them but can’t see or hear them, and nothing is recorded.',
    '- Staff who handle reports must use two-factor sign-in. Their authenticator secrets are stored encrypted (AES-256-GCM).',
    '- Every time staff open a report, a reported photo, a verification selfie or reported voice evidence, it’s recorded in an audit log.',
    f.ageCheck &&
      '- Age checks are done by an outside provider. We keep only the result (over 18 or not), the method and the date: never a document, photo or date of birth.',
    f.faith &&
      '- Faith and observance answers are stored only with your consent, never used for ranking, and never sent to partner communities. Withdrawing consent deletes them.',
    f.identity &&
      '- Your gender identity and pronouns are shown only to matches unless you choose otherwise, and are never sent to partner communities.',
    '',
    '## Who else gets data',
    '',
    f.partners > 0
      ? `- ${f.partners} partner communit${f.partners === 1 ? 'y' : 'ies'}: only if you choose to be seen there, and only your card (first name, age, photos, short bio). Never your email, location, faith or identity details.`
      : '- No partner communities at the moment.',
    f.externalAi
      ? '- Text suggestions (icebreakers, bio ideas) use an AI service outside our server: [name the provider]. Only the text needed for the suggestion is sent.'
      : '- No outside AI service: suggestions are made on our server.',
    '- [List any other provider: email delivery, backups, hosting.]',
    '',
    '## How long we keep it',
    '',
    `- Chats after an unmatch: ${UNMATCHED_CHAT_RETENTION_DAYS} days.`,
    `- Closed reports: ${RESOLVED_REPORT_RETENTION_DAYS} days; moderation decisions: ${MODERATION_LOG_RETENTION_DAYS} days; security audit log: ${AUDIT_LOG_RETENTION_DAYS} days.`,
    '- Your account and everything in it: until you delete it, which you can do at any time in the app.',
    '',
    '## If something goes wrong',
    '',
    'We record every security incident. If one puts your data at risk, we tell the authority and you as the law requires. [Name the authority, e.g. the Privacy Protection Authority in Israel.]',
    '',
    `Questions: ${f.contact ?? '[contact email]'}.`,
  ]);
}

