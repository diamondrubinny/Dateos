/**
 * Phase 57, after `expo export`: makes the web app installable and able to open without the
 * server (docs/phases/PHASE-57.md).
 * - index.html: the manifest (served on the app's domain from the community's branding), the
 *   theme colour and the home-screen icons.
 * - sw.js: a service worker that keeps this build's own code (the same for everyone) and nothing
 *   else: never anything from the API, which is another origin.
 * Usage: node scripts/web-pwa.mjs
 */
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const dist = join(dirname(fileURLToPath(import.meta.url)), '..', 'dist');

async function files(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await files(path)));
    else out.push(path);
  }
  return out;
}

// 1. index.html: what browsers look for to offer "Install app" / "Add to Home screen".
const indexFile = join(dist, 'index.html');
const tags = [
  '<link rel="manifest" href="/manifest.webmanifest">',
  '<meta name="theme-color" content="#7C3AED">',
  '<link rel="apple-touch-icon" href="/icons/apple-touch-icon.png">',
  '<meta name="mobile-web-app-capable" content="yes">',
  '<meta name="apple-mobile-web-app-capable" content="yes">',
];
let html = await readFile(indexFile, 'utf8');
const missing = tags.filter((tag) => !html.includes(tag));
if (missing.length) html = html.replace('</head>', `${missing.join('')}</head>`);
await writeFile(indexFile, html);

// 2. sw.js: the app's code (hashed file names, so a new build is new files), the page and icons.
const all = (await files(dist)).map((f) => `/${relative(dist, f).split(sep).join('/')}`);
const precache = [
  '/index.html',
  ...all.filter((p) => p.startsWith('/_expo/static/') || p.startsWith('/icons/')),
].sort();
const hash = createHash('sha256');
for (const path of precache) hash.update(path).update(await readFile(join(dist, path)));
const version = hash.digest('hex').slice(0, 16);

const sw = `// NexaHeart web app service worker (phase 57), generated by scripts/web-pwa.mjs. Build ${version}.
// It keeps this build's own code so the app opens when the server or the connection is away, and
// then the app says so itself. It never stores anything from the API (another origin): no
// profiles, messages or photos.
const CACHE = 'nexaheart-app-${version}';
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(PRECACHE))
      .then(() => self.skipWaiting()),
  );
});

// A new build replaces the old copy.
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith('nexaheart-app-') && key !== CACHE)
            .map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  // Only the app's own files: never the API or any other site.
  if (url.origin !== self.location.origin) return;
  if (url.pathname === '/sw.js' || url.pathname === '/manifest.webmanifest') return;
  if (request.mode === 'navigate') {
    // The page from the network first, so a new version shows at once; this build's copy when
    // the server doesn't answer (or answers with an error page).
    event.respondWith(
      fetch(request)
        .then((response) =>
          response.status >= 500 ? caches.match('/index.html').then((hit) => hit || response) : response,
        )
        .catch(() => caches.match('/index.html').then((hit) => hit || Response.error())),
    );
    return;
  }
  // The app's code and images: names change with every build, so a stored copy is always right.
  if (url.pathname.startsWith('/_expo/static/') || url.pathname.startsWith('/assets/') || url.pathname.startsWith('/icons/')) {
    event.respondWith(
      caches.match(request).then(
        (hit) =>
          hit ||
          fetch(request).then((response) => {
            if (response.ok) {
              const copy = response.clone();
              void caches.open(CACHE).then((cache) => cache.put(request, copy));
            }
            return response;
          }),
      ),
    );
  }
});
`;
await writeFile(join(dist, 'sw.js'), sw);
process.stdout.write(
  `PWA: ${precache.length} files kept by the service worker, build ${version}\n`,
);
